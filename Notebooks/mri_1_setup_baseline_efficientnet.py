    params = model.count_params() / 1e6

    clean_results[name] = {'accuracy': acc, 'f1_weighted': f1, 'params_M': params}
    print(f"\n{name} clean results: acc={acc:.4f}, F1={f1:.4f}, params={params:.2f}M")

    model.save(f'{PROJECT_ROOT}/models/checkpoints/{name.lower()}_clean.keras')
    del model, base, train_ds_m, val_ds_m, test_ds_m
