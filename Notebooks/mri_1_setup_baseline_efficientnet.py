# Same protocol as EfficientNetB3: Stage 1 (frozen, 10 epochs) + Stage 2 (unfrozen last 30, 15 epochs)

models_to_train = {
    'MobileNetV2': tf.keras.applications.MobileNetV2,
    'ResNet50':    tf.keras.applications.ResNet50,
    'InceptionV3': tf.keras.applications.InceptionV3,
    'VGG16':       tf.keras.applications.VGG16,
}

# InceptionV3 needs larger input size; others fine at 224x224
input_sizes = {
    'MobileNetV2': (224,224), 'ResNet50': (224,224),
    'InceptionV3': (299,299), 'VGG16': (224,224)
}
preprocess_fns = {
    'MobileNetV2': tf.keras.applications.mobilenet_v2.preprocess_input,
    'ResNet50':    tf.keras.applications.resnet50.preprocess_input,
    'InceptionV3': tf.keras.applications.inception_v3.preprocess_input,
    'VGG16':       tf.keras.applications.vgg16.preprocess_input,
}

clean_results = {}

for name, ModelClass in models_to_train.items():
    print(f"\n{'='*55}\n{name}\n{'='*55}")
    tf.keras.backend.clear_session()
    gc.collect()

    img_size = input_sizes[name]
    preprocess_fn = preprocess_fns[name]

    # Rebuild train/val/test datasets at this model's required input size
    def prep(ds_dir, split, subset=None, val_split=None, shuffle=True):
        kwargs = dict(seed=42, image_size=img_size, batch_size=BATCH_SIZE,
                      label_mode='int', class_names=CLASS_NAMES, shuffle=shuffle)
        if val_split:
            kwargs.update(validation_split=val_split, subset=subset)
        raw = tf.keras.utils.image_dataset_from_directory(f'{ds_dir}/{split}', **kwargs)
        return raw.map(lambda x,y: (preprocess_fn(x), y), num_parallel_calls=tf.data.AUTOTUNE).prefetch(tf.data.AUTOTUNE)

    train_ds_m = prep(CLAHE_DIR, 'Training', subset='training', val_split=0.1)
    val_ds_m   = prep(CLAHE_DIR, 'Training', subset='validation', val_split=0.1)
    test_ds_m  = prep(CLAHE_DIR, 'Testing', shuffle=False)

    base = ModelClass(include_top=False, weights='imagenet', input_shape=(*img_size,3))
    base.trainable = False
    inputs = tf.keras.layers.Input(shape=(*img_size,3))
    x = base(inputs, training=False)
    x = tf.keras.layers.GlobalAveragePooling2D()(x)
    x = tf.keras.layers.Dropout(0.3)(x)
    outputs = tf.keras.layers.Dense(len(CLASS_NAMES), activation='softmax')(x)
    model = tf.keras.Model(inputs, outputs)

    # Stage 1: frozen
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-3),
                  loss='sparse_categorical_crossentropy', metrics=['accuracy'])
    model.fit(train_ds_m, validation_data=val_ds_m, epochs=10,
              callbacks=[tf.keras.callbacks.EarlyStopping(monitor='val_accuracy', patience=5, restore_best_weights=True)],
              verbose=1)

    # Stage 2: unfreeze last 30 layers
    base.trainable = True
    for layer in base.layers[:-30]:
        layer.trainable = False
    model.compile(optimizer=tf.keras.optimizers.Adam(1e-5),
                  loss='sparse_categorical_crossentropy', metrics=['accuracy'])
    model.fit(train_ds_m, validation_data=val_ds_m, epochs=15,
              callbacks=[
                  tf.keras.callbacks.EarlyStopping(monitor='val_accuracy', patience=5, restore_best_weights=True),
                  tf.keras.callbacks.ReduceLROnPlateau(monitor='val_accuracy', factor=0.5, patience=2)
              ], verbose=1)

